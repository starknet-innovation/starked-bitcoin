pub const SEGWIT_HEIGHT: u32 = 481824;

/// The block's context, from the header chain.
pub const Ctx = struct {
    height: u32,
    prev_mtp: u32,
    /// Tests only: build the witness of an invalid block anyway (wrapping arithmetic, values truncated
    /// to their limbs), to check that the AIR rejects it.
    force: bool = false,
    /// The 11 predecessors' headers, oldest first (D-043 part 3); required at and above the CSV height.
    anc: ?*const [11][80]u8 = null,

    pub fn cutoff(self: Ctx, raw: []const u8) u32 {
        return if (self.height >= CSV_HEIGHT) self.prev_mtp else std.mem.readInt(u32, raw[68..72], .little);
    }
    pub fn bip34(self: Ctx) bool {
        return self.height >= BIP34_HEIGHT;
    }
    pub fn csv(self: Ctx) bool {
        return self.height >= CSV_HEIGHT;
    }
    pub fn segwit(self: Ctx) bool {
        return self.height >= SEGWIT_HEIGHT;
    }
};

/// Public inputs 0–6: length, transaction count, height, prevMtp, and the three activation bits.
/// The block's public inputs: length, transaction count, height, the previous MTP's low 16 bits, the
/// activation bits (BIP34, CSV, segwit), and the previous MTP's high 16 bits.
/// Below the CSV height the MTP is unused and its limbs are 0 (D-043 part 3).
pub fn pubs(raw: []const u8, ntx: u32, ctx: Ctx) [8]M31 {
    const m: u32 = if (ctx.csv()) ctx.prev_mtp else 0;
    return .{
        f(raw.len),                    f(ntx),                         f(ctx.height),
        f(m & 0xffff),                 f(@intFromBool(ctx.bip34())),   f(@intFromBool(ctx.csv())),
        f(@intFromBool(ctx.segwit())), f(m >> 16),
    };
}

/// The 11 predecessors' headers of a sample (testdata, oldest first).
pub fn ancOf(comptime h: []const u8) *const [11][80]u8 {
    return @ptrCast(@embedFile("testdata:anc_" ++ h));
}

fn f(x: anytype) M31 {
    return M31.fromCanonical(@intCast(x));
}

fn invOrZero(x: M31) M31 {
    return x.inv() catch M31.zero();
}

/// What the checks read and claim, for the other components' witnesses.
pub const Out = struct {
    /// Block positions read (byte table multiplicities).
    reads: []u32,
    /// Range-table values used (with repetition).
    ranges: []u32,
    /// Non-empty scripts `(start, len)`, in row order.
    scripts: [][2]u32,
    /// Witness bytes (marker, flag and witness sections) and segwit transactions.
    w: u32,
    nseg: u32,
    /// The coinbase output taken as the witness commitment, if any: its script `(start, len)`.
    commit: ?[2]u32,
    cutoff: u32,
};

pub const Error = error{ NonFinal, ValueOutOfRange, EmptyOutputs, NullPrevout, OutOfMemory };

/// Fills the check columns of `cols` (already generated by `fields.generate`) and returns what the
/// other components need. Fails on a block the checks reject (the AIR would be unsatisfiable).
pub fn fill(a: std.mem.Allocator, cols: [][]M31, raw: []const u8, rows: []const fields.Row, ctx: Ctx) Error!Out {
    const n = cols[0].len;
    const one = M31.one();
    var reads = std.ArrayList(u32).empty;
    var ranges = std.ArrayList(u32).empty;
    var scripts = std.ArrayList([2]u32).empty;
    const cutoff = ctx.cutoff(raw);

    // Per transaction: its finality mode (0 zero, 1 lock-time, 2 sequences) and TY.
    var modes = std.ArrayList([2]u8).empty;
    {
        var i: usize = 0;
        while (i < rows.len) : (i += 1) {
            if (rows[i].kind != K_TXH) continue;
            var j = i;
            var all_ff = true;
            while (rows[j].kind != K_LOCK) : (j += 1) {
                if (rows[j].kind == K_IN) {
                    const r = rows[j];
                    if (std.mem.readInt(u32, raw[r.start + r.len - 4 ..][0..4], .little) != 0xffffffff) all_ff = false;
                }
            }
            const lt = std.mem.readInt(u32, raw[rows[j].start..][0..4], .little);
            const ty: u8 = @intFromBool(lt >= 500000000);
            const thr = if (ty == 1) cutoff else ctx.height;
            const mode: [2]u8 = if (lt == 0) .{ 0, 0 } else if (lt < thr) .{ 1, ty } else if (all_ff) .{ 2, 0 } else if (ctx.force) .{ 1, ty } else return error.NonFinal;
            try modes.append(a, mode);
        }
    }

    // The coinbase outputs: which match the commitment pattern; the last one is the commitment.
    var commit_row: ?usize = null;
    if (ctx.segwit()) {
        for (rows, 0..) |r, i| {
            if (r.kind == K_LOCK) break;
            if (r.kind != K_OUT) continue;
            const ss = r.start + r.off + r.pref;
            if (r.val >= 38 and std.mem.eql(u8, raw[ss..][0..6], &PATTERN)) commit_row = i;
        }
    }

    var txi: u32 = 0;
    var tlo: u64 = 0;
    var thi: u64 = 0;
    var w: u32 = 0;
    var nseg: u32 = 0;
    var aft: u32 = 0;
    const hasc: u32 = @intFromBool(commit_row != null);
    for (0..n) |i| {
        const pad = i >= rows.len;
        const r: fields.Row = if (!pad) rows[i] else .{ .kind = fields.K_PAD, .start = @intCast(raw.len), .len = 0 };
        // Padding rows keep the last transaction's mode (the mode columns are constant past it).
        const mode = if (r.kind == K_BLK) [2]u8{ 0, 0 } else modes.items[@min(txi, modes.items.len - 1)];
        var rg = [_]u32{0} ** N_RG;
        cols[FZ][i] = f(@intFromBool(mode[0] == 0));
        cols[FL][i] = f(@intFromBool(mode[0] == 1));
        cols[FS][i] = f(@intFromBool(mode[0] == 2));
        cols[TY][i] = f(mode[1]);
        const base: u32 = if (r.kind == K_IN) r.start + r.len - 4 else r.start;
        cols[BASEC][i] = f(base);
        const nby: usize = switch (r.kind) {
            K_OUT => 8,
            K_LOCK, K_IN => 4,
            else => 0,
        };
        var by = [_]u32{0} ** 8;
        for (0..nby) |j| {
            by[j] = raw[base + j];
            cols[BY0 + j][i] = f(by[j]);
            try reads.append(a, base + @as(u32, @intCast(j)));
        }
        const zt = txi == 0;
        cols[ZT][i] = f(@intFromBool(zt));
        cols[INVT][i] = invOrZero(f(txi));
        const gin = r.kind == K_IN and !zt;
        cols[GIN][i] = f(@intFromBool(gin));
        if (r.kind == K_NOUT) {
            if (r.val == 0 and !ctx.force) return error.EmptyOutputs;
            cols[INVN][i] = invOrZero(f(r.val));
        }
        const ss: u32 = r.start + r.off + r.pref;
        cols[SSC][i] = f(ss);
        cols[ZV][i] = f(@intFromBool(r.val == 0));
        cols[INVV][i] = invOrZero(f(r.val));
        if ((r.kind == K_IN or r.kind == K_OUT) and r.val != 0) try scripts.append(a, .{ ss, r.val });

        // Values and the running total.
        if (r.kind == K_TXH) {
            tlo = 0;
            thi = 0;
        }
        if (r.kind == K_OUT) {
            if ((by[7] != 0 or by[6] > 7) and !ctx.force) return error.ValueOutOfRange;
            const vlo: u64 = by[0] + 256 * @as(u64, by[1]) + 65536 * @as(u64, by[2]);
            const vhi: u64 = by[3] + 256 * @as(u64, by[4]) + 65536 * @as(u64, by[5]) + 16777216 * @as(u64, by[6]);
            var s = tlo + vlo;
            var car: u64 = 0;
            if (s >= 1 << 24) {
                s -= 1 << 24;
                car = 1;
            }
            tlo = s;
            thi += vhi + car;
            cols[CAR][i] = f(car);
            const bor: u64 = @intFromBool(tlo > MAXLO);
            if (thi + bor > MAXHI and !ctx.force) return error.ValueOutOfRange;
            const dlo = MAXLO +% (bor << 24) -% tlo;
            const dhi = MAXHI -% thi -% bor;
            cols[BOR][i] = f(bor);
            rg[0] = (7 -% by[6]) & 0xff;
            rg[1] = @intCast(tlo & 0xff);
            rg[2] = @intCast((tlo >> 8) & 0xff);
            rg[3] = @intCast((tlo >> 16) & 0xff);
            rg[4] = @intCast(dlo & 0xff);
            rg[5] = @intCast((dlo >> 8) & 0xff);
            rg[6] = @intCast((dlo >> 16) & 0xff);
            rg[7] = @intCast(dhi & 0xff);
            rg[8] = @intCast((dhi >> 8) & 0xff);
            rg[9] = @intCast((dhi >> 16) & 0xff);
            rg[10] = @intCast((dhi >> 24) & 0xff);
            rg[11] = (7 -% rg[10]) & 0xff;
        }
        cols[TLO][i] = f(tlo);
        cols[THI][i] = f(thi);

        // Non-null prevouts after the coinbase: a position whose byte differs from the null outpoint.
        var mmb = false;
        if (gin) {
            var q: u32 = 0;
            while (q < 36) : (q += 1) {
                const b = raw[r.start + q];
                if ((q < 32 and b != 0) or (q >= 32 and b != 0xff)) break;
            }
            if (q == 36) {
                if (!ctx.force) return error.NullPrevout;
                q = 0;
            }
            cols[QH][i] = f(q >> 5);
            for (0..5) |j| cols[QB0 + j][i] = f((q >> @intCast(j)) & 1);
            cols[AQ][i] = f(r.start + q);
            cols[BQ][i] = f(raw[r.start + q]);
            const exp: u32 = if (q >= 32) 255 else 0;
            cols[EXPQ][i] = f(exp);
            cols[INVQ][i] = invOrZero(f(raw[r.start + q]).sub(f(exp)));
            try reads.append(a, r.start + q);
        }

        // Finality.
        if (r.kind == K_LOCK) {
            const lt: u32 = by[0] | (by[1] << 8) | (by[2] << 16) | (by[3] << 24);
            if (mode[0] == 1 and mode[1] == 0) {
                rg[0] = (127 -% by[2]) & 0xff;
                const d = ctx.height -% 1 -% lt;
                rg[1] = d & 0xff;
                rg[2] = (d >> 8) & 0xff;
                rg[3] = (d >> 16) & 0xff;
            } else if (mode[0] == 1) {
                const elo = (lt & 0xffff) + 0x10000 - 0x6500;
                const b2: u32 = @intFromBool(elo < 0x10000);
                const el = elo - (1 - b2) * 0x10000;
                const eh = (lt >> 16) -% 0x1DCD -% b2;
                cols[B2][i] = f(b2);
                rg[4] = el & 0xff;
                rg[5] = el >> 8;
                rg[6] = eh & 0xff;
                rg[7] = (eh >> 8) & 0xff;
                const clo = cutoff & 0xffff;
                const chi = cutoff >> 16;
                const dlo = clo + 0x10000 - (lt & 0xffff) -% 1;
                const brw: u32 = @intFromBool(dlo < 0x10000);
                const dl = dlo -% (1 - brw) * 0x10000;
                const dh = chi -% (lt >> 16) -% brw;
                cols[BRW][i] = f(brw);
                rg[8] = dl & 0xff;
                rg[9] = (dl >> 8) & 0xff;
                rg[10] = dh & 0xff;
                rg[11] = (dh >> 8) & 0xff;
            }
        }
        cols[GZ][i] = f(@intFromBool(r.kind == K_LOCK and mode[0] == 0));
        cols[GS][i] = f(@intFromBool(r.kind == K_IN and mode[0] == 2));
        cols[GL0][i] = f(@intFromBool(r.kind == K_LOCK and mode[0] == 1 and mode[1] == 0));
        cols[GL1][i] = f(@intFromBool(r.kind == K_LOCK and mode[0] == 1 and mode[1] == 1));
        cols[CLO][i] = f(cutoff & 0xffff);
        cols[CHI][i] = f(cutoff >> 16);

        // Witness bytes (2 per segwit head, each witness token's length) and segwit count.
        if (i > 0) {
            var dw: u32 = 0;
            if (r.kind == K_TXH and r.seg) dw = 2;
            if (r.kind == fields.K_WCNT or r.kind == fields.K_WITEM) dw = r.len;
            cols[DW][i] = f(dw);
            w += dw;
            if (r.kind == K_TXH and r.seg) nseg += 1;
        }
        cols[WB][i] = f(w);
        cols[NS][i] = f(nseg);

        // Commitment candidates.
        const g0 = r.kind == K_OUT and zt and ctx.segwit();
        cols[G0][i] = f(@intFromBool(g0));
        const isc = commit_row != null and commit_row.? == i;
        cols[ISC][i] = f(@intFromBool(isc));
        cols[AFT][i] = f(aft);
        cols[HASC][i] = f(hasc);
        const reqc = g0 and !isc;
        cols[REQC][i] = f(@intFromBool(reqc));
        const req = reqc and (hasc == 0 or aft == 1);
        cols[REQ][i] = f(@intFromBool(req));
        if (req) {
            if (r.val <= 37) {
                cols[MML][i] = one;
                rg[12] = 37 - r.val;
            } else {
                var q: u32 = 0;
                while (q < 6 and raw[ss + q] == PATTERN[q]) : (q += 1) {}
                if (q == 6) {
                    std.debug.assert(ctx.force);
                    q = 0;
                }
                mmb = true;
                cols[MMB][i] = one;
                cols[OH0 + q][i] = one;
                cols[AQ][i] = f(ss + q);
                cols[BQ][i] = f(raw[ss + q]);
                cols[EXPQ][i] = f(PATTERN[q]);
                cols[INVQ][i] = invOrZero(f(raw[ss + q]).sub(f(PATTERN[q])));
                try reads.append(a, ss + q);
            }
        }
        if (isc) aft += 1;

        for (0..N_RG) |j| {
            cols[RG0 + j][i] = f(rg[j]);
            try ranges.append(a, rg[j]);
        }
        if (r.kind == K_LOCK) txi += 1;
    }
    var commit: ?[2]u32 = null;
    if (commit_row) |cr| {
        const r = rows[cr];
        commit = .{ r.start + r.off + r.pref, r.val };
    }
    return .{
        .reads = try reads.toOwnedSlice(a),
        .ranges = try ranges.toOwnedSlice(a),
        .scripts = try scripts.toOwnedSlice(a),
        .w = w,
        .nseg = nseg,
        .commit = commit,
        .cutoff = cutoff,
    };
}

/// The tables' main columns: range multiplicities and opcode multiplicities.
pub fn tables(a: std.mem.Allocator, log_size: u32, ranges: []const u32, opcodes: []const u8) ![][]M31 {
    const n = @as(usize, 1) << @intCast(log_size);
    if (n < 256) return error.TooSmall;
    const cols = try a.alloc([]M31, 2);
    for (cols) |*c| {
        c.* = try a.alloc(M31, n);
        @memset(c.*, M31.zero());
    }
    for (ranges) |v| cols[0][v] = cols[0][v].add(M31.one());
    for (opcodes) |b| cols[1][b] = cols[1][b].add(M31.one());
    return cols;
}

