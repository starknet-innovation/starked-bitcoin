test "block checks: the samples satisfy the extended fields AIR" {
    const ir = @import("../air/ir.zig");
    const interp = @import("../air/interp.zig");
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const fields_air = (try ir.Air.parseJson(a, fields.json)).value;
    const all = samples_small ++ samples_large;
    for (all) |s| {
        const rows = try fields.tokenize(a, s.raw);
        const log_size: u32 = @max(8, std.math.log2_int_ceil(usize, rows.len + 1));
        const fm = try fields.generate(a, log_size, s.raw, rows);
        const out = try fill(a, fm, s.raw, rows, s.ctx);
        const p = pubs(s.raw, rows[0].val, s.ctx);
        const tr = interp.RowTrace{ .log_size = log_size, .pubs = &p, .preprocessed = @ptrCast(try fields_air.genPreprocessed(a, log_size)), .main = @ptrCast(fm) };
        if (try interp.firstViolation(a, fields_air, tr)) |v| {
            std.debug.print("height {d}: row {d} (kind {d}) violates constraint {d}\n", .{ s.ctx.height, v.row, rows[@min(v.row, rows.len - 1)].kind, v.constraint });
            return error.TestUnexpectedResult;
        }
        std.debug.print("height {d}: {d} rows, {d} scripts, W {d}, segwit txs {d}, commitment {any}\n", .{ s.ctx.height, rows.len, out.scripts.len, out.w, out.nseg, out.commit });
    }
}
